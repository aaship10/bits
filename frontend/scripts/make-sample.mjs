// Regenerates src/sample.js from the first 24 rows of the starter kit's sample_test_input.csv.
// Usage: npm run sample -- ../sample_test_input.csv
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = process.argv[2] || '../sample_test_input.csv';
const lines = readFileSync(src, 'utf8').trim().split(/\r?\n/);
const head = lines[0].split(',').map((s) => s.trim().toLowerCase());
const col = (n) => {
  const i = head.indexOf(n);
  if (i < 0) throw new Error(`column ${n} not found in ${src}`);
  return i;
};
const [ti, ci, hi, si] = ['timestamp', 'ambient_temp_c', 'humidity_pct', 'solar_irradiance_wm2'].map(col);
const rows = lines.slice(1, 25).map((l) => {
  const p = l.split(',');
  return {
    timestamp: p[ti].trim(),
    ambient_temp_c: Number(p[ci]),
    humidity_pct: Number(p[hi]),
    solar_irradiance_wm2: Number(p[si]),
  };
});
const out = `// Generated by scripts/make-sample.mjs from the first 24 rows of sample_test_input.csv.
export const IS_PLACEHOLDER = false;
export const SAMPLE_ROWS = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(fileURLToPath(new URL('../src/sample.js', import.meta.url)), out);
console.log(`wrote ${rows.length} rows to src/sample.js`);
